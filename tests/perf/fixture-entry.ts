/**
 * Perf fixture worker (T15 resource budgets, wave-5 worker C).
 *
 * Bundled on the fly by bench-stream.mjs (esbuild) and hosted by Miniflare 5.
 * It mounts the REAL content download router and the REAL upload chunk router
 * — the exact production code paths for streaming bytes — but injects fixture
 * providers at the existing dependency seams (ContentRouteDeps.readProvider /
 * UploadRouterDeps.providerFor), exactly like tests/integration does. No
 * production code branches on this file and no bytes ever touch disk: both
 * fixture providers stream a deterministic generated pattern.
 *
 * Bindings expected (declared by bench-stream.mjs):
 *   DB                — real D1 (migrations applied + minimal seed rows), so
 *                       getMount/authorizeMount/listReadPool/upload projections
 *                       run real SQL like production.
 *   UPLOAD_SESSION    — the real SQLite Durable Object class (exported below).
 *   PERF_FILE_BYTES   — decimal size of the generated fixture object.
 *   PERF_SHA256       — hex sha256 of the generated byte stream (upload verify).
 *   PERF_MD5          — hex md5 of the generated byte stream.
 *
 * Operation counters (D1 statements, DO stub fetches, provider calls, bytes
 * through the provider boundary) are exposed via GET /_perf/counters so the
 * Node harness can diff them per scenario — this is how "DO operation counts"
 * are measured without a production seam.
 */

