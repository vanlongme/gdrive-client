// Wiring: real routers, injected fixtures, counted D1/DO surface
// ---------------------------------------------------------------------------

const ADMIN_ACTOR = {
  kind: "user" as const,
  user: {
    id: "admin-1",
    name: "Perf Admin",
    email: "perf-admin@test",
    role: "admin" as const,
    disabled: false,
    createdAt: new Date(0).toISOString(),
  },
  sessionId: "sess-perf",
};

export default {
  async fetch(request: Request, env: any, ctx: any): Promise<Response> {
    const url = new URL(request.url);
    if (url.pathname === "/_perf/counters") {
      return Response.json(counters);
    }
    if (url.pathname === "/_perf/reset") {
      counters.d1 = { prepare: 0, exec: 0, batch: 0, first: 0, all: 0, run: 0, raw: 0 };
      counters.doStubFetches = 0;
      counters.providerRead = {};
      counters.providerWrite = {};
      counters.upstreamBytesRead = 0;
      counters.upstreamBytesWritten = 0;
      return new Response("ok");
    }

    const readProvider = makeReadProvider(env);
    const writeProvider = makeWriteProvider(env);

    const app = new Hono();
    app.use("/api/*", async (c, next) => {
      c.set("requestId", "req-perf");
      await next();
    });
    app.route(
      "/api/v1/mounts",
      createContentRouter({
        resolveSessionActor: () => Promise.resolve(ADMIN_ACTOR),
        readProvider,
      }),
    );
    app.route(
      "/api/v1/uploads",
      createUploadRouter({
        providerFor: () => writeProvider,
        readProviderFor: () => readProvider,
        resolveActorFn: () => Promise.resolve(ADMIN_ACTOR),
        sessionNamespace: (e) => wrapDoNamespace(e.UPLOAD_SESSION),
      }),
    );

    const countedEnv = { ...env, DB: wrapDb(env.DB) };
    return app.fetch(request, countedEnv, ctx);
  },
};
