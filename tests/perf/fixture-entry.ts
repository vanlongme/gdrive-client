// ---------------------------------------------------------------------------
// Deterministic generated body — one 1 MiB block of a fixed pattern, reused
// for every slice so upstream memory stays ~1 MiB regardless of object size.
// The byte pattern is data, not identity: benches never checksum the
// download path, and the upload path verifies against the hashes the harness
// computes over the identical pattern (PERF_SHA256/PERF_MD5 bindings).
// ---------------------------------------------------------------------------

const SLICE = 1024 * 1024;
const block = new Uint8Array(SLICE);
for (let i = 0; i < SLICE; i += 1) block[i] = (i * 31 + 7) & 0xff;

function generatedStream(totalBytes: bigint): ReadableStream<Uint8Array> {
  let sent = 0n;
  return new ReadableStream<Uint8Array>({
    pull(controller) {
      if (sent >= totalBytes) {
        controller.close();
        return;
      }
      const n = Number(
        totalBytes - sent > BigInt(SLICE) ? BigInt(SLICE) : totalBytes - sent,
      );
      controller.enqueue(block.subarray(0, n));
      sent += BigInt(n);
    },
  });
}

async function drain(stream: ReadableStream<Uint8Array>): Promise<bigint> {
  const reader = stream.getReader();
  let n = 0n;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) return n;
    n += BigInt(value.byteLength);
    counters.upstreamBytesWritten += value.byteLength;
  }
}

// ---------------------------------------------------------------------------
// Operation counters
// ---------------------------------------------------------------------------

const counters = {
  d1: { prepare: 0, exec: 0, batch: 0, first: 0, all: 0, run: 0, raw: 0 },
  doStubFetches: 0,
  providerRead: {} as Record<string, number>,
  providerWrite: {} as Record<string, number>,
  upstreamBytesRead: 0,
  upstreamBytesWritten: 0,
};

function bump(table: Record<string, number>, key: string): void {
  table[key] = (table[key] ?? 0) + 1;
}

/* The proxies below intentionally use `any`: this entry is bundled by
 * esbuild for workerd and is outside every tsconfig include, so the D1/DO
 * shapes are asserted by the runtime contract, not the compiler. */
function wrapStatement(stmt: any): any {
  return new Proxy(stmt, {
    get(target, prop, receiver) {
      const value = Reflect.get(target, prop, receiver);
      if (prop === "bind") {
        return (...args: unknown[]) =>
          wrapStatement(value.apply(target, args));
      }
      if (prop === "first" || prop === "all" || prop === "run" || prop === "raw") {
        return (...args: unknown[]) => {
          counters.d1[prop] += 1;
          return value.apply(target, args);
        };
      }
      return typeof value === "function" ? value.bind(target) : value;
    },
  });
}

function wrapDb(db: any): any {
  return new Proxy(db, {
    get(target, prop, receiver) {
      const value = Reflect.get(target, prop, receiver);
      if (prop === "prepare") {
        return (query: string) => {
          counters.d1.prepare += 1;
          return wrapStatement(target.prepare(query));
        };
      }
      if (prop === "exec" || prop === "batch") {
        return (...args: unknown[]) => {
          counters.d1[prop as "exec" | "batch"] += 1;
          return value.apply(target, args);
        };
      }
      return typeof value === "function" ? value.bind(target) : value;
    },
  });
}

function wrapDoNamespace(ns: any): any {
  return new Proxy(ns, {
    get(target, prop, receiver) {
      const value = Reflect.get(target, prop, receiver);
      if (prop === "get") {
        return (id: unknown) => {
          const stub = target.get(id);
          return new Proxy(stub, {
            get(stubTarget, stubProp, stubReceiver) {
              const stubValue = Reflect.get(stubTarget, stubProp, stubReceiver);
              if (stubProp === "fetch") {
                return (...args: unknown[]) => {
                  counters.doStubFetches += 1;
                  return stubValue.apply(stubTarget, args);
                };
              }
              return typeof stubValue === "function"
                ? stubValue.bind(stubTarget)
                : stubValue;
            },
          });
        };
      }
      return typeof value === "function" ? value.bind(target) : value;
    },
  });
}
// ---------------------------------------------------------------------------
// Fixture providers (the only fake seam — identical to integration tests)
// ---------------------------------------------------------------------------

const PERF_FILE_ID = "perf-file-1";
const SESSION_URI =
  "https://www.googleapis.com/upload/drive/v3/files?uploadType=resumable&upload_id=perf-session-1";

function fixtureMeta(env: Record<string, string>, id: string): DriveFileMeta {
  return {
    id,
    name: "perf.bin",
    mimeType: "application/octet-stream",
    size: env.PERF_FILE_BYTES as DriveFileMeta["size"],
    modifiedTime: "2026-10-01T00:00:00.000Z",
    trashed: false,
    parents: ["parent-1"],
    driveId: "drive-1",
    sha256Checksum: env.PERF_SHA256,
    md5Checksum: env.PERF_MD5,
    hasThumbnail: false,
    capabilities: { canDownload: true, canTrash: true },
  };
}

function makeReadProvider(
  env: Record<string, string>,
): ServiceAccountContentReadProvider {
  const total = BigInt(env.PERF_FILE_BYTES ?? "0");
  const metaFor = (id: string): DriveFileMeta => fixtureMeta(env, id);
  const content = (range?: ByteRange): UpstreamContent => {
    const start = range?.start ?? 0n;
    const end = range?.end ?? total - 1n;
    const length = end - start + 1n;
    return {
      status: range === undefined ? 200 : 206,
      contentType: "application/octet-stream",
      contentLength: length,
      ...(range === undefined
        ? {}
        : { contentRange: `bytes ${start}-${end}/${total}` }),
      body: generatedStream(length),
    };
  };
  return {
    getReadMetadata(input) {
      bump(counters.providerRead, "getReadMetadata");
      return Promise.resolve(metaFor(input.ref.id));
    },
    getRevision(input) {
      bump(counters.providerRead, "getRevision");
      return Promise.resolve({
        id: input.revisionId,
        size: env.PERF_FILE_BYTES as DriveFileMeta["size"],
        mimeType: "application/octet-stream",
        keepForever: true,
      });
    },
    openContent(input) {
      bump(counters.providerRead, "openContent");
      counters.upstreamBytesRead += Number(
        input.range === undefined
          ? total
          : input.range.end - input.range.start + 1n,
      );
      return Promise.resolve(content(input.range));
    },
    openThumbnail() {
      bump(counters.providerRead, "openThumbnail");
      return Promise.resolve(content());
    },
    exportDocument() {
      bump(counters.providerRead, "exportDocument");
      return Promise.resolve(content());
    },
  };
}

function makeWriteProvider(
  env: Record<string, string>,
): OAuthCatalogWriteProvider {
  const total = BigInt(env.PERF_FILE_BYTES ?? "0");
  const meta = () => fixtureMeta(env, PERF_FILE_ID);
  return {
    listChildren() {
      bump(counters.providerWrite, "listChildren");
      return Promise.resolve({ entries: [] });
    },
    search() {
      bump(counters.providerWrite, "search");
      return Promise.resolve({ entries: [] });
    },
    getMetadata(input) {
      bump(counters.providerWrite, "getMetadata");
      // R9 destination check: parents/drives must look writable.
      if (input.ref.id === "parent-1" || input.ref.id === "drive-1") {
        return Promise.resolve({
          ...meta(),
          id: input.ref.id,
          mimeType: "application/vnd.google-apps.folder",
          parents: undefined,
          capabilities: { canAddChildren: true, canTrash: true },
        });
      }
      return Promise.resolve(meta());
    },
    generateId() {
      bump(counters.providerWrite, "generateId");
      return Promise.resolve(PERF_FILE_ID);
    },
    createFolder() {
      bump(counters.providerWrite, "createFolder");
      return Promise.resolve({
        ...meta(),
        mimeType: "application/vnd.google-apps.folder",
      });
    },
    startUpload() {
      bump(counters.providerWrite, "startUpload");
      return Promise.resolve({
        kind: "resumable" as const,
        sessionUri: SESSION_URI,
        generatedFileId: PERF_FILE_ID,
      });
    },
    async putChunk(input) {
      bump(counters.providerWrite, "putChunk");
      const received = await drain(input.body);
      if (received !== BigInt(input.chunkBytes)) {
        throw new Error(
          `fixture putChunk length mismatch: ${received} != ${input.chunkBytes}`,
        );
      }
      const confirmed = input.offset + received;
      if (confirmed >= total) {
        return { kind: "completed" as const, file: meta() };
      }
      return { kind: "incomplete" as const, confirmedOffset: confirmed };
    },
    probeUpload() {
      bump(counters.providerWrite, "probeUpload");
      return Promise.resolve({
        kind: "incomplete" as const,
        confirmedOffset: 0n,
      });
    },
    verifyFile(input) {
      bump(counters.providerWrite, "verifyFile");
      return Promise.resolve({ ...meta(), id: input.ref.id });
    },
    trashFile() {
      bump(counters.providerWrite, "trashFile");
      return Promise.resolve();
    },
  };
}

