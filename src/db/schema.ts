// Tombstone contract: rows are never deleted. Detail cleanup clears only the
// transient `summary` progress blob and stamps detail_purged_at; state,
// result, generated_file_id and pinned identity stay for the installation
// lifetime so replayed idempotency keys still answer the final outcome.
// Pinned writer columns are immutable identity snapshots (no FK on purpose):
// a tombstone must keep resolving the original writer even if the connection
// row is later disabled or replaced.
export const uploadOperations = sqliteTable(
  'upload_operations',
  {
    id: text('id').primaryKey(),
    ownerId: text('owner_id')
      .notNull()
      .references(() => users.id),
    mountId: text('mount_id')
      .notNull()
      .references(() => mounts.id),
    batchId: text('batch_id').references(() => uploadBatches.id),
    nodeId: text('node_id'),
    kind: text('kind', { enum: UPLOAD_OPERATION_KINDS }).notNull(),
    idempotencyHash: text('idempotency_hash').notNull(),
    inputHash: text('input_hash').notNull(),
    generatedFileId: text('generated_file_id'),
    pinnedOauthConnectionId: text('pinned_oauth_connection_id').notNull(),
    pinnedPrincipalId: text('pinned_principal_id').notNull(),
    pinnedOauthClientId: text('pinned_oauth_client_id').notNull(),
    pinnedProjectId: text('pinned_project_id').notNull(),
    state: text('state', { enum: UPLOAD_OPERATION_STATES })
      .notNull()
      .default('created'),
    result: text('result'),
    summary: text('summary'),
    projectionVersion: integer('projection_version').notNull().default(0),
    detailPurgedAt: integer('detail_purged_at', { mode: 'timestamp_ms' }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull(),
    updatedAt: integer('updated_at', { mode: 'timestamp_ms' }).notNull(),
    completedAt: integer('completed_at', { mode: 'timestamp_ms' }),
  },
  (t) => [
    unique('upload_operations_owner_idempotency_uq').on(
      t.ownerId,
      t.idempotencyHash,
    ),
    index('upload_operations_mount_idx').on(t.mountId),
    index('upload_operations_owner_created_idx').on(t.ownerId, t.createdAt),
    index('upload_operations_generated_file_idx').on(t.generatedFileId),
  ],
);

